#!/usr/bin/env python3
"""Run the Go Attack main adversary evaluation against cp505 victims.

This follows the repository's paper_evaluations.yml structure: one trained
adversary is matched against four cp505 victim settings, with a fixed number
of games per matchup.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Iterable


VICTIM_MODEL = "kata1-b40c256-s11840935168-d2898845681.bin.gz"


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument("--project-root", type=Path, default=Path.cwd())
    p.add_argument("--go-attack-root", type=Path)
    p.add_argument("--katago-bin", type=Path)
    p.add_argument("--torch-dir", type=Path)
    p.add_argument("--opencl-icd-dir", type=Path)
    p.add_argument("--output-dir", type=Path, required=True)
    p.add_argument("--adversary-name", choices=["cyclic", "pass"], required=True)
    p.add_argument("--adversary-model", type=Path)
    p.add_argument("--victim-model", type=Path)
    p.add_argument("--num-games-per-matchup", type=int, default=1000)
    p.add_argument("--num-game-threads", type=int, default=128)
    p.add_argument("--adversary-visits", type=int, default=600)
    p.add_argument("--adversary-algorithm", default="AMCTS-S")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--parse-only", action="store_true")
    return p.parse_args()


def default_paths(args: argparse.Namespace) -> None:
    project = args.project_root
    if args.go_attack_root is None:
        args.go_attack_root = project / "external" / "go_attack"
    if args.katago_bin is None:
        args.katago_bin = args.go_attack_root / "engines" / "KataGo-custom" / "cpp" / "katago"
    if args.torch_dir is None:
        args.torch_dir = project / "external" / "third_party" / "libtorch"
    if args.opencl_icd_dir is None:
        args.opencl_icd_dir = project / "external" / "third_party" / "opencl_icd"
    if args.adversary_model is None:
        args.adversary_model = args.go_attack_root / "sabaki" / "models" / "adv" / args.adversary_name / "model.bin.gz"
    if args.victim_model is None:
        args.victim_model = args.go_attack_root / "sabaki" / "models" / "victims" / VICTIM_MODEL


def require_paths(paths: Iterable[Path]) -> None:
    missing = [str(p) for p in paths if not p.exists()]
    if missing:
        raise SystemExit("Missing required paths:\n" + "\n".join(missing))


def victims(victim_model: Path) -> list[dict[str, object]]:
    return [
        {
            "name": "cp505h-v2048",
            "visits": 2048,
            "model": victim_model,
            "extra": {"passingBehavior": "avoid-pass-alive-territory"},
        },
        {
            "name": "cp505h-v1",
            "visits": 1,
            "model": victim_model,
            "extra": {"passingBehavior": "avoid-pass-alive-territory"},
        },
        {"name": "cp505-v2048", "visits": 2048, "model": victim_model, "extra": {}},
        {"name": "cp505-v1", "visits": 1, "model": victim_model, "extra": {}},
    ]


def write_bot(
    lines: list[str],
    bot_index: int,
    model: Path,
    name: str,
    visits: int,
    algorithm: str,
    extra: dict[str, str] | None = None,
) -> None:
    use_graph = "true" if algorithm == "MCTS" else "false"
    lines.extend(
        [
            f"nnModelFile{bot_index} = {model}",
            f"botName{bot_index} = {name}",
            f"maxVisits{bot_index} = {visits}",
            f"searchAlgorithm{bot_index} = {algorithm}",
            f"useGraphSearch{bot_index} = {use_graph}",
        ]
    )
    for key, value in (extra or {}).items():
        lines.append(f"{key}{bot_index} = {value}")


def write_match_config(args: argparse.Namespace, config_path: Path) -> None:
    victim_specs = victims(args.victim_model)
    adv_index = len(victim_specs)
    adv_name = f"{args.adversary_name}-adv-v{args.adversary_visits}-{args.adversary_algorithm}"
    total_games = len(victim_specs) * args.num_games_per_matchup
    lines = [
        "# Generated by r019r1_main_adversary_evaluation.py",
        "logSearchInfo = false",
        f"numGamesTotal = {total_games}",
        f"numGameThreads = {args.num_game_threads}",
        "useNHWC = false",
        "",
        f"numBots = {len(victim_specs) + 1}",
        "secondaryBots = " + ",".join(str(i) for i in range(len(victim_specs))),
        "secondaryBots2 = " + str(adv_index),
        "",
    ]
    for i, victim in enumerate(victim_specs):
        write_bot(
            lines,
            i,
            victim["model"],  # type: ignore[arg-type]
            str(victim["name"]),
            int(victim["visits"]),
            "MCTS",
            victim["extra"],  # type: ignore[arg-type]
        )
        lines.append("")
    write_bot(lines, adv_index, args.adversary_model, adv_name, args.adversary_visits, args.adversary_algorithm)
    lines.append("")
    config_path.write_text("\n".join(lines), encoding="utf-8")


def parse_sgf_props(text: str) -> dict[str, str]:
    props: dict[str, str] = {}
    for key in ("PB", "PW", "RE"):
        m = re.search(rf"{key}\[([^\]]*)\]", text)
        if m:
            props[key] = m.group(1)
    return props


def iter_sgf_records(path: Path) -> Iterable[tuple[str, str]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    starts = [m.start() for m in re.finditer(r"\(;FF\[", text)]
    if not starts:
        return
    starts.append(len(text))
    for i, start in enumerate(starts[:-1]):
        record = text[start : starts[i + 1]].strip()
        if record:
            yield f"{path}#{i}", record


def summarize_sgfs(sgf_dir: Path) -> dict[str, object]:
    rows = []
    for sgf in sorted(list(sgf_dir.rglob("*.sgf")) + list(sgf_dir.rglob("*.sgfs"))):
        if sgf.stat().st_size == 0:
            continue
        for sgf_id, record in iter_sgf_records(sgf):
            props = parse_sgf_props(record)
            result = props.get("RE", "")
            winner = result[:1] if "+" in result or result in {"B", "W"} else ""
            black = props.get("PB", "")
            white = props.get("PW", "")
            black_is_adv = any(token in black.lower() for token in ("adv", "cyclic", "pass"))
            white_is_adv = any(token in white.lower() for token in ("adv", "cyclic", "pass"))
            adv_color = "B" if black_is_adv else "W" if white_is_adv else ""
            victim_name = white if black_is_adv else black if white_is_adv else ""
            rows.append(
                {
                    "sgf": sgf_id,
                    "victim": victim_name,
                    "black": black,
                    "white": white,
                    "result": result,
                    "winner": winner,
                    "adversary_color": adv_color,
                    "adversary_win": bool(adv_color and winner == adv_color),
                }
            )
    groups: dict[str, dict[str, object]] = {}
    for row in rows:
        victim = str(row["victim"])
        group = groups.setdefault(victim, {"num_games": 0, "adversary_wins": 0, "results": {}})
        group["num_games"] = int(group["num_games"]) + 1
        if row["adversary_win"]:
            group["adversary_wins"] = int(group["adversary_wins"]) + 1
        results = group["results"]
        assert isinstance(results, dict)
        results[str(row["result"])] = int(results.get(str(row["result"]), 0)) + 1
    for group in groups.values():
        games = int(group["num_games"])
        wins = int(group["adversary_wins"])
        group["adversary_win_rate"] = wins / games if games else None
    total = len(rows)
    adv_wins = sum(1 for r in rows if r["adversary_win"])
    return {
        "num_sgfs": total,
        "adversary_wins": adv_wins,
        "adversary_win_rate": (adv_wins / total) if total else None,
        "by_victim": groups,
        "rows": rows,
    }


def main() -> int:
    args = parse_args()
    default_paths(args)
    require_paths([args.go_attack_root, args.katago_bin, args.torch_dir, args.opencl_icd_dir, args.adversary_model, args.victim_model])

    out = args.output_dir
    cfg_dir = out / "configs"
    sgf_dir = out / "sgfs"
    log_dir = out / "logs"
    for d in (cfg_dir, sgf_dir, log_dir):
        d.mkdir(parents=True, exist_ok=True)

    cell = f"{args.adversary_name}_main_v{args.adversary_visits}_ngpm{args.num_games_per_matchup}"
    config_path = cfg_dir / f"{cell}.cfg"
    log_path = log_dir / f"{cell}.log"
    stdout_path = log_dir / f"{cell}.stdout.log"
    write_match_config(args, config_path)

    env = os.environ.copy()
    env["LD_LIBRARY_PATH"] = f"/usr/lib/x86_64-linux-gnu:{args.torch_dir / 'lib'}:{env.get('LD_LIBRARY_PATH', '')}"
    env["OCL_ICD_VENDORS"] = str(args.opencl_icd_dir)
    command = [
        str(args.katago_bin),
        "match",
        "-config",
        str(args.go_attack_root / "configs" / "match-1gpu.cfg"),
        "-config",
        str(config_path),
        "-sgf-output-dir",
        str(sgf_dir),
        "-log-file",
        str(log_path),
    ]
    manifest = {
        "cell": cell,
        "command": command,
        "env": {k: env[k] for k in ("LD_LIBRARY_PATH", "OCL_ICD_VENDORS")},
        "config": str(config_path),
        "output_dir": str(out),
        "num_games_per_matchup": args.num_games_per_matchup,
    }
    if args.parse_only:
        summary = summarize_sgfs(sgf_dir)
        summary.update({"status": "parsed", "returncode": None, "cell": cell, "config": str(config_path), "log": str(log_path), "stdout_log": str(stdout_path)})
        (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
        print(json.dumps({k: v for k, v in summary.items() if k != "rows"}, indent=2))
        return 0
    (out / "run_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    if args.dry_run:
        print(json.dumps(manifest, indent=2))
        return 0

    with stdout_path.open("w", encoding="utf-8") as stdout_file:
        proc = subprocess.run(command, env=env, stdout=stdout_file, stderr=subprocess.STDOUT, text=True)

    summary = summarize_sgfs(sgf_dir)
    summary.update({"status": "done" if proc.returncode == 0 else "failed", "returncode": proc.returncode, "cell": cell, "config": str(config_path), "log": str(log_path), "stdout_log": str(stdout_path)})
    (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in summary.items() if k != "rows"}, indent=2))
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
